const originalAttr = new WeakMap();
export function getLanguage(){
  try{return localStorage.getItem('vr-logistics-language')==='hi'?'hi':'en';}catch{return 'en';}
}
export function setLanguage(lang){
  const locale=lang==='hi'?'hi':'en';
  try{localStorage.setItem('vr-logistics-language',locale);}catch{}
  document.documentElement.lang=locale;
}
export function t(value){
  return getLanguage()==='hi'?translateStatic(value):String(value??'');
}
export function localize(root:Document|Element=document){
  const locale=getLanguage();
  document.documentElement.lang=locale;
  const tree=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes=[];while(tree.nextNode())nodes.push(tree.currentNode);
  for(const node of nodes){
    if(node.parentElement?.closest('.quote-preview, [data-react-i18n], script, style'))continue;
    const raw=originalText.has(node)?originalText.get(node):node.nodeValue;
    if(!originalText.has(node))originalText.set(node,raw);
    node.nodeValue=locale==='hi'?translateStatic(raw):raw;
  }
  const elements=root.querySelectorAll?root.querySelectorAll('[placeholder],[title],[aria-label]'):[];
  for(const el of elements){
    let cached=originalAttr.get(el);
    if(!cached){cached={};originalAttr.set(el,cached);}
    for(const attr of ['placeholder','title','aria-label']){
      if(!el.hasAttribute(attr))continue;
      if(!(attr in cached))cached[attr]=el.getAttribute(attr);
      el.setAttribute(attr,locale==='hi'?translateStatic(cached[attr]):cached[attr]);
    }
  }
  document.querySelectorAll<HTMLButtonElement>('.language-switch [data-lang]').forEach(button=>{
    const active=button.dataset.lang===locale;
    button.classList.toggle('active',active);
    button.setAttribute('aria-pressed',String(active));
  });
}
function translateStatic(value){
  const str=String(value??''),trimmed=str.trim();
  const arrow=trimmed.match(/^(.*?)(\s+[↗→↘☎↓]+)$/);
  const phrase=arrow?arrow[1].trim():trimmed;
  const exact=translations[phrase];
  if(exact)return str.replace(trimmed,exact+(arrow?arrow[2]:''));
  for(const [regex,replace] of regexRules){
    if(regex.test(trimmed))return str.replace(trimmed,trimmed.replace(regex,replace));
  }
  return str;
}
